/// Text zum Key, Platzhalter `{name}` werden ersetzt. Fehlt der Key, bricht
/// es im Debug-Modus ab, im Release erscheint der Key.
String kt(String key, [Map<String, Object> args = const {}]) {
  final text = karteTexte[key];
  assert(text != null, 'Fehlender Copy-Key: $key');
  var out = text ?? key;
  args.forEach((name, value) {
    out = out.replaceAll('{$name}', '$value');
  });
  return out;
}
